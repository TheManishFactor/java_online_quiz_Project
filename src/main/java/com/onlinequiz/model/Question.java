package com.onlinequiz.model;

import com.onlinequiz.exception.InvalidQuestionException;
import com.onlinequiz.exception.ValidationException;
import com.onlinequiz.interfaces.Identifiable;
import com.onlinequiz.util.Validation;

import java.util.Locale;

/**
 * Multiple-choice question with four options and a correct answer label (A-D).
 */
public class Question implements Identifiable {

    private int id;
    private int quizId;
    private String questionText;
    private String optionA;
    private String optionB;
    private String optionC;
    private String optionD;
    private String correctAnswer;

    public Question(int id, int quizId, String questionText,
                    String optionA, String optionB, String optionC, String optionD,
                    String correctAnswer) {
        setId(id);
        setQuizId(quizId);
        setQuestionText(questionText);
        setOptions(optionA, optionB, optionC, optionD);
        setCorrectAnswer(correctAnswer);
    }

    /**
     * Constructor overloading: id is generated by the database, so new questions
     * use this overload.
     */
    public Question(int quizId, String questionText,
                    String optionA, String optionB, String optionC, String optionD,
                    String correctAnswer) {
        this(0, quizId, questionText, optionA, optionB, optionC, optionD, correctAnswer);
    }

    @Override
    public final int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = Validation.requireNonNegative(id, "Question id");
    }

    public int getQuizId() {
        return quizId;
    }

    public void setQuizId(int quizId) {
        this.quizId = Validation.requirePositive(quizId, "Quiz id");
    }

    public String getQuestionText() {
        return questionText;
    }

    public void setQuestionText(String questionText) {
        this.questionText = requireQuestionText(questionText, "Question text");
    }

    public String getOptionA() {
        return optionA;
    }

    public void setOptionA(String optionA) {
        this.optionA = requireQuestionText(optionA, "Option A");
    }

    public String getOptionB() {
        return optionB;
    }

    public void setOptionB(String optionB) {
        this.optionB = requireQuestionText(optionB, "Option B");
    }

    public String getOptionC() {
        return optionC;
    }

    public void setOptionC(String optionC) {
        this.optionC = requireQuestionText(optionC, "Option C");
    }

    public String getOptionD() {
        return optionD;
    }

    public void setOptionD(String optionD) {
        this.optionD = requireQuestionText(optionD, "Option D");
    }

    /**
     * Replaces all four options at once after validating each one.
     */
    public void setOptions(String optionA, String optionB, String optionC, String optionD) {
        String[] options = validateOptions(new String[]{optionA, optionB, optionC, optionD});
        this.optionA = options[0];
        this.optionB = options[1];
        this.optionC = options[2];
        this.optionD = options[3];
    }

    /**
     * Array-based access used by the quiz screen, which renders four options.
     */
    public String[] getOptions() {
        return new String[]{optionA, optionB, optionC, optionD};
    }

    public String getOption(char label) {
        switch (Character.toUpperCase(label)) {
            case 'A':
                return optionA;
            case 'B':
                return optionB;
            case 'C':
                return optionC;
            case 'D':
                return optionD;
            default:
                throw new ValidationException("Option label must be A, B, C or D");
        }
    }

    public String getCorrectAnswer() {
        return correctAnswer;
    }

    public void setCorrectAnswer(String correctAnswer) {
        this.correctAnswer = normalizeAnswer(correctAnswer);
    }

    public boolean isCorrect(String selectedAnswer) {
        if (selectedAnswer == null) {
            return false;
        }
        String normalized = selectedAnswer.trim().toUpperCase(Locale.ROOT);
        return correctAnswer.equals(normalized);
    }

    /**
     * Normalizes and validates the answer label. Only A, B, C or D are accepted.
     *
     * Unchecked exception: a malformed question is a data-integrity bug, so the
     * caller is not forced to declare it; {@link InvalidQuestionException} still
     * gives the failure a precise, catchable type.
     */
    public static String normalizeAnswer(String answer) {
        String normalized;
        try {
            normalized = Validation.requireText(answer, "Correct answer").toUpperCase(Locale.ROOT);
        } catch (ValidationException error) {
            throw new InvalidQuestionException(error.getMessage(), error);
        }
        if (!"A".equals(normalized) && !"B".equals(normalized)
                && !"C".equals(normalized) && !"D".equals(normalized)) {
            throw new InvalidQuestionException("Correct answer must be A, B, C or D");
        }
        return normalized;
    }

    private static String[] validateOptions(String[] options) {
        for (int index = 0; index < options.length; index++) {
            options[index] = requireQuestionText(
                    options[index], "Option " + (char) ('A' + index));
        }
        return options;
    }

    /**
     * Translates the generic validation failure into the question-specific type
     * while keeping the original exception as the cause for logging.
     */
    private static String requireQuestionText(String value, String fieldName) {
        try {
            return Validation.requireText(value, fieldName);
        } catch (ValidationException error) {
            throw new InvalidQuestionException(error.getMessage(), error);
        }
    }

    @Override
    public String toString() {
        return "Question{id=" + id + ", quizId=" + quizId + ", text='" + questionText
                + "', correct='" + correctAnswer + "'}";
    }
}
